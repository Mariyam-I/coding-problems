package com.cc._02_declare_and_initialize_array;

public class DeclareAndInitializeArray {

	public static void main(String[] args) {

		/*
		//Declaring an array
		int[] arr ; */
		
		
		
		/*
		//Allocating space for 5 elements
		int[] arr;
		arr = new int[5]; */
		
		
		
		/*
		//Declaring & initializing an array of size 5
		int[] arr = new int[5]; */
		
		
		
		/*
		//Initializing with values directly
		int[] arr = {10,20,30,40,50}; */
		
		
		
		/*
		//Using new keyword
		int[] arr = new int[] {5,15,25,35,45};*/
	}

}
