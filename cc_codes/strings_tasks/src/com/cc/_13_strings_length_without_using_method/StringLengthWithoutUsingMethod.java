package com.cc._13_strings_length_without_using_method;

public class StringLengthWithoutUsingMethod {

	public static void main(String[] args) {

		String s = "I am Learning Java";
		char[] srr = s.toCharArray();
		
		System.out.println("Length without using length method = " + srr.length);
		
	}

}

//Length without using length method = 18
